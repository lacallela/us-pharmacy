function sleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

function postToDpaste(title, content) {
  const contentFile = path.join(__dirname, 'temp_dpaste.txt');
  fs.writeFileSync(contentFile, content, 'utf8');

  try {
    const cmd = `curl.exe -s --retry 3 --retry-delay 2 -x http://127.0.0.1:10809 --data-urlencode "content@${contentFile}" -d "syntax=md" -d "title=${encodeURIComponent(title)}" -d "expiry_days=365" https://dpaste.com/api/v2/`;
    const res = execSync(cmd).toString().trim();
    return res;
  } finally {
    if (fs.existsSync(contentFile)) fs.unlinkSync(contentFile);
  }
}

